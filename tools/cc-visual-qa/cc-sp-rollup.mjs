// cc-sp-rollup: large-site guardrails EXCEPTIONS rollup (JOB0024-108).
// Aggregates the per-page completeness-gate verdicts (+ triage scope-sheet +
// worklist) into ONE exceptions report so the operator reviews only FAILURES and
// FLAGGED-SKIPPED pages — not every page. PASS pages are counted, not listed.
//
//   node cc-sp-rollup.mjs <jobDir> [--verdicts <dir>] [--out-md <path>]
//
// Reads from <jobDir>:
//   qa-verdict-*.json   per-page gate verdicts (or under --verdicts dir)
//   scope-sheet.json    (optional) triage output — flagged-skipped + archived
//   worklist.json       (optional) wave statuses
// Writes: <jobDir>/exceptions.json + <jobDir>/exceptions.md
import { readdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";

const argv = process.argv.slice(2);
if (!argv[0] || argv[0].startsWith("--")) { console.error("usage: cc-sp-rollup.mjs <jobDir> [--verdicts <dir>] [--out-md <path>]"); process.exit(2); }
const jobDir = argv[0];
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
const verdictsDir = val("--verdicts", jobDir);
const outMd = val("--out-md", join(jobDir, "exceptions.md"));
const outJson = join(jobDir, "exceptions.json");

const readJson = (p) => { try { return JSON.parse(readFileSync(p, "utf8")); } catch { return null; } };

function failReason(v) {
  const parts = [];
  const mi = (v.missing?.images || []).length, ml = (v.missing?.links || []).length, mt = (v.missing?.text || []).length;
  const cs = v.imagesCheck?.countShortfall || 0;
  if (mi) parts.push(`${mi} image(s) missing`);
  if (cs) parts.push(`${cs} image(s) short`);
  if (ml) parts.push(`${ml} link(s) missing`);
  if (mt) parts.push(`${mt} text block(s) missing`);
  if (v.sections && v.sections.ok === false) parts.push("too few sections");
  if (v.published && v.published.ok === false) parts.push("publish problem");
  return parts.join(", ") || "incomplete";
}

// 1) gate verdicts
const verdictFiles = existsSync(verdictsDir)
  ? readdirSync(verdictsDir).filter(f => /^qa-verdict-.*\.json$/.test(f))
  : [];
const built = [];
for (const f of verdictFiles) {
  const v = readJson(join(verdictsDir, f));
  if (!v) continue;
  const label = basename(f).replace(/^qa-verdict-/, "").replace(/\.json$/, "");
  built.push({ file: label, title: v.builtTitle || label, pass: !!v.pass, reason: v.pass ? null : failReason(v) });
}

// 2) triage scope-sheet: flagged-skipped (kept but not buildable) + archived
const scope = readJson(join(jobDir, "scope-sheet.json")) || [];
const flaggedSkipped = scope.filter(r => r.keep && r.flagReason && !r.buildable)
  .map(r => ({ file: r.file, title: r.title, reason: r.flagReason }));
const archivedCount = scope.filter(r => !r.keep).length;

// 3) worklist failed (defensive — gate verdict is the source of truth for fails)
const worklist = readJson(join(jobDir, "worklist.json"));
const worklistFailed = worklist ? worklist.pages.filter(p => p.status === "failed").map(p => p.file) : [];

const passed = built.filter(b => b.pass);
const failed = built.filter(b => !b.pass);

const report = {
  job: basename(jobDir.replace(/\/+$/, "")),
  summary: {
    built: built.length, pass: passed.length, fail: failed.length,
    flaggedSkipped: flaggedSkipped.length, archived: archivedCount,
    scopeTotal: scope.length || null,
  },
  failures: failed,
  flaggedSkipped,
  worklistFailed,
};
writeFileSync(outJson, JSON.stringify(report, null, 2));

// markdown — exceptions only
const md = [];
md.push(`# Exceptions — ${report.job}`);
md.push("");
const s = report.summary;
md.push(`**Built ${s.built}** · ✅ pass ${s.pass} · ❌ fail ${s.fail} · ⚑ flagged-skipped ${s.flaggedSkipped} · 🗄 archived ${s.archived}` +
  (s.scopeTotal ? ` · scope total ${s.scopeTotal}` : ""));
md.push("");
if (!failed.length && !flaggedSkipped.length) {
  md.push("✅ **No exceptions** — every built page passed the gate and nothing was flagged-skipped.");
} else {
  if (failed.length) {
    md.push("## ❌ Gate failures (fix or re-run)");
    md.push("| Page | Title | Reason |");
    md.push("|---|---|---|");
    for (const f of failed) md.push(`| \`${f.file}\` | ${f.title} | ${f.reason} |`);
    md.push("");
  }
  if (flaggedSkipped.length) {
    md.push("## ⚑ Flagged — NOT built (flag-don't-fake; rebuild = JOB0024-109)");
    md.push("| Page | Title | Why |");
    md.push("|---|---|---|");
    for (const f of flaggedSkipped) md.push(`| \`${f.file}\` | ${f.title} | ${f.reason} |`);
    md.push("");
  }
}
md.push("");
md.push(`_${s.pass} passing page(s) omitted (review exceptions only). Generated by cc-sp-rollup._`);
writeFileSync(outMd, md.join("\n"));

console.log(`rollup: built ${s.built} (pass ${s.pass}/fail ${s.fail}), flagged-skipped ${s.flaggedSkipped}, archived ${s.archived} -> ${outMd}`);
process.exit(0);
